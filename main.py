st.divider()

st.header("📈 그래프 2. 일관객 합계 TOP 5 영화")

st.write(
    "전체 기간 동안 일관객 합계가 가장 큰 5편의 날짜별 일관객 변화를 비교합니다."
)


# 영화별 전체 기간 일관객 합계 계산
top5_movies = (
    df.groupby("영화명")["일관객"]
    .sum()
    .sort_values(ascending=False)
    .head(5)
    .index
    .tolist()
)


# TOP 5 영화만 추출
top5_df = df[df["영화명"].isin(top5_movies)].copy()

# 날짜순 정렬
top5_df = top5_df.sort_values(["날짜", "영화명"])


# 선 그래프 생성
fig2 = px.line(
    top5_df,
    x="날짜",
    y="일관객",
    color="영화명",
    markers=True,
    title="일관객 합계 TOP 5 영화의 날짜별 일관객 변화",
    labels={
        "날짜": "날짜",
        "일관객": "일관객 수",
        "영화명": "영화"
    },
    hover_data={
        "날짜": "|%Y년 %m월 %d일",
        "영화명": True,
        "일관객": ":,.0f"
    }
)


# 마우스를 올렸을 때 표시되는 내용
fig2.update_traces(
    hovertemplate=(
        "영화: %{fullData.name}<br>"
        "날짜: %{x|%Y년 %m월 %d일}<br>"
        "일관객: %{y:,.0f}명"
        "<extra></extra>"
    )
)


fig2.update_layout(
    xaxis_title="날짜",
    yaxis_title="일관객 수(명)",
    hovermode="x unified",
    height=600,
    legend_title="영화"
)


# 그래프 출력
st.plotly_chart(
    fig2,
    use_container_width=True
)


